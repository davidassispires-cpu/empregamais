'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const Model=require('../demo-paineis-modelo.js');
const now=Date.parse('2026-10-14T00:00:00Z');
const demo=Model.create(null,()=>now);
let state=demo.snapshot();
assert.equal(state.jobs.length,6);
assert.equal(state.applications.length,68);
assert.equal(state.applications.filter(a=>a.profileId===state.profile.id).length,1);
const vacancy=state.jobs.find(j=>j.cargo==='Vendedor(a)');
const application=demo.apply(vacancy.id);
assert.equal(application.profileId,state.profile.id);
assert.equal(demo.snapshot().applications.filter(a=>a.jobId===vacancy.id).length,13);
assert.throws(()=>demo.apply(vacancy.id),/já se candidatou/);
assert.throws(()=>demo.apply(state.jobs.find(j=>j.status==='pausada').id),/não está recebendo/);
demo.updateStage(application.id,'Em análise');
assert.equal(demo.snapshot().applications.find(a=>a.id===application.id).stage,'Em análise');
assert.throws(()=>demo.updateStage(application.id,'Inventada'),/etapa válida/);
const message=demo.sendMessage(application.id,'empresa','Seu currículo está em análise.','Portal');
assert.equal(demo.snapshot().messages.find(m=>m.id===message.id).appId,application.id);
demo.sendMessage(application.id,'candidato','Obrigada!','Portal');
assert.equal(demo.snapshot().messages[0].from,'candidato');
assert.throws(()=>demo.sendMessage(application.id,'empresa','   '),/Escreva/);
assert.throws(()=>demo.schedule({appId:application.id,date:new Date(now-60000).toISOString()}),/futuros/);
const interview=demo.schedule({appId:application.id,date:new Date(now+86400000).toISOString(),duration:30,format:'Vídeo'});
assert.equal(demo.snapshot().applications.find(a=>a.id===application.id).stage,'Entrevista agendada');
demo.confirmInterview(interview.id);
assert(demo.snapshot().interviews.find(i=>i.id===interview.id).confirmed);
demo.cancelInterview(interview.id);
assert.equal(demo.snapshot().interviews.find(i=>i.id===interview.id).status,'cancelada');
assert.throws(()=>demo.confirmInterview(interview.id),/indisponível/);
demo.setPlan('basico');
assert.equal(demo.plan().vagas,3);
assert.equal(demo.available(),1);
assert.throws(()=>demo.favorite(application.id),/plano pago/);
const published=demo.publish({cargo:'TESTE ADMINISTRATIVO',cidade:'Betim',uf:'MG',salario:2000});
assert.equal(published.status,'ativa');
assert.equal(demo.available(),0);
assert.throws(()=>demo.publish({cargo:'Outro',cidade:'Betim',uf:'MG'}),/limite/);
demo.setPlan('mensal');
assert.equal(demo.plan().vagas,8);
demo.favorite(application.id);
assert(demo.snapshot().applications.find(a=>a.id===application.id).favorite);
let service=demo.activateService(published.id,'destaque');
assert.deepEqual(service,{included:false,price:9.9});
assert.throws(()=>demo.activateService(published.id,'destaque'),/já está ativo/);
demo.setPlan('trimestral');
assert.equal(demo.plan().vagas,30);
assert.equal(demo.serviceBalance('urgente'),2);
service=demo.activateService(published.id,'urgente');
assert(service.included);
assert.equal(demo.serviceBalance('urgente'),1);
demo.setPlan('semestral');assert.equal(demo.plan().vagas,70);
demo.setPlan('anual');assert.equal(demo.plan().vagas,150);
demo.jobAction(published.id,'pause');
assert.equal(demo.snapshot().jobs.find(j=>j.id===published.id).status,'pausada');
demo.jobAction(published.id,'resume');
assert.equal(demo.snapshot().jobs.find(j=>j.id===published.id).status,'ativa');
demo.jobAction(published.id,'close');
assert.throws(()=>demo.jobAction(published.id,'resume'),/encerrada/);
demo.saveProfile({nome:'Ana Atualizada',email:'ana-atualizada@example.com',cidade:'Contagem'});
assert.equal(demo.snapshot().applications.find(a=>a.id===application.id).nome,'Ana Atualizada');
demo.saveResume({summary:'Experiência em atendimento.',skills:'Excel'});
assert.equal(demo.snapshot().profile.resume.summary,'Experiência em atendimento.');
assert.throws(()=>demo.attachResume({name:'arquivo.exe',size:1}),/PDF ou Word/);
demo.attachResume({name:'curriculo-ficticio.pdf',size:100});
assert.equal(demo.snapshot().profile.resume.fileName,'curriculo-ficticio.pdf');
demo.saveCompany({nome:'Empresa de Teste',email:'empresa-teste@example.com'});
assert(demo.snapshot().jobs.every(j=>j.empresa==='Empresa de Teste'));
demo.verifyCompany({name:'documento-ficticio.pdf',size:10});
assert.equal(demo.snapshot().company.verificacao,'Em análise');
assert.throws(()=>demo.verifyCompany({name:'documento.html',size:1}),/PDF ou imagem/);
demo.support('Dúvida','Como funciona a demonstração?');
assert.equal(demo.snapshot().tickets.length,1);
demo.setPremium(true);assert(demo.snapshot().profile.premium);
const reopened=Model.create(JSON.parse(JSON.stringify(demo.snapshot())),()=>now);
assert.deepEqual(reopened.snapshot(),demo.snapshot(),'Demo actions survive reload');
const invalid=Model.create({version:1},()=>now);
assert.equal(invalid.snapshot().applications.length,68);
let networkCalls=0,storageReads=0;
const fakeWindow={EM_DEMO_PANEL:true,sessionStorage:{getItem(){storageReads++;return 'real-account-token';}},fetch(){networkCalls++;throw Error('Must not call production');},document:{addEventListener(type,fn){if(type==='DOMContentLoaded')fn();}}};
vm.runInNewContext(fs.readFileSync(require.resolve('../planos-config.js'),'utf8'),{window:fakeWindow});
(async()=>{
 assert.equal(await fakeWindow.EMPlanos.refreshBalance(true),null);
 await assert.rejects(()=>fakeWindow.EMPlanos.rpc('em_plan_balance'),/demonstração/);
 assert.equal(networkCalls,0);
 assert.equal(storageReads,0,'Demo must not inspect a real account token');
 const ui=fs.readFileSync(require.resolve('../demo-paineis.js'),'utf8');
 assert(!/\bfetch\s*\(|XMLHttpRequest|WebSocket/.test(ui));
 new vm.Script(ui);
 console.log('PASS: candidate → company application, stages, messages and interviews; all five plans, limits and benefits; job lifecycle, profiles, resume, verification, support, persistence and zero real account/network access.');
})().catch(e=>{console.error(e);process.exitCode=1;});
